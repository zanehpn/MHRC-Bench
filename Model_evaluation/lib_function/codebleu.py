# =========================

def f1_from_sets(ref_set: Set[Tuple[str, str]], pred_set: Set[Tuple[str, str]]) -> float:
    if not ref_set and not pred_set:
        return 1.0
    if not ref_set or not pred_set:
        return 0.0
    inter = len(ref_set & pred_set)
    p = inter / len(pred_set)
    r = inter / len(ref_set)
    return (2 * p * r / (p + r)) if (p + r) else 0.0


