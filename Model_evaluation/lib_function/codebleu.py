RE_CPP_ASSIGN = re.compile(r'(?m)^\s*([A-Za-z_]\w*)\s*=\s*(.+?);')
RE_CPP_LHS_DECL_ASSIGN = re.compile(
    r'(?m)^\s*(?:const\s+)?(?:unsigned\s+)?'
    r'(?:int|long|short|char|float|double|bool|auto|size_t|ap_uint<[^>]+>|ap_int<[^>]+>|hls::stream<[^>]+>|'
    r'[A-Za-z_]\w*::[A-Za-z_]\w*|[A-Za-z_]\w*)\s+([A-Za-z_]\w*)\s*=\s*(.+?);'
)
RE_CPP_ID = re.compile(r'\b([A-Za-z_]\w*)\b')
CPP_STOP = {
    "if","for","while","return","switch","case","break","continue","sizeof","true","false","nullptr",
    "static","const","unsigned","signed","int","long","short","char","float","double","void","auto",
    "template","typename","class","struct","union","enum","namespace","using","new","delete"
}

def dataflow_edges_hls(code: str) -> Set[Tuple[str, str]]:
    edges: Set[Tuple[str, str]] = set()
    for m in RE_CPP_LHS_DECL_ASSIGN.finditer(code):
        lhs, rhs = m.group(1), m.group(2)
        uses = [x for x in RE_CPP_ID.findall(rhs) if x not in CPP_STOP]
        for u in uses:
            if u != lhs:
                edges.add((lhs, u))
    for m in RE_CPP_ASSIGN.finditer(code):
        lhs, rhs = m.group(1), m.group(2)
        uses = [x for x in RE_CPP_ID.findall(rhs) if x not in CPP_STOP]
        for u in uses:
            if u != lhs:
                edges.add((lhs, u))
    return edges


