@dataclass
class CodeBLEUScore:
    bleu: float
    weighted_bleu: float
    syntax: float
    dataflow: float
    codebleu: float


def _keyword_map_for_lang(lang: str) -> Dict[str, float]:
    if lang == "chisel":
        return make_keyword_weight_map(KW_CHISEL_SCALA, base_weight=1.0)
    if lang == "systemverilog":
        return make_keyword_weight_map(KW_SYSTEMVERILOG, base_weight=1.0)
    if lang == "vhdl":
        return make_keyword_weight_map(KW_VHDL, base_weight=1.0)
    if lang == "hls":
        return make_keyword_weight_map(KW_HLS_CPP, base_weight=1.0)
    return {}


def evaluate_codebleu(
    lang: str,
    prediction: str,
    reference: str,
    alpha: float = 0.25,
    beta: float = 0.25,
    gamma: float = 0.25,
    delta: float = 0.25,
) -> CodeBLEUScore:
    """
    Shared CodeBLEU routine; language controls keyword weights + syntax/dataflow rules.
    """
    pred_norm = normalize_code(prediction, lang=lang)
    ref_norm = normalize_code(reference, lang=lang)

    pred_tokens = code_tokenize(pred_norm)
    ref_tokens = code_tokenize(ref_norm)

    smoothie = SmoothingFunction().method1
    bleu = sentence_bleu([ref_tokens], pred_tokens, smoothing_function=smoothie)

    wmap = _keyword_map_for_lang(lang)
    wbleu = weighted_sentence_bleu(ref_tokens, pred_tokens, wmap, default_w=0.5)

    syn = syntax_match_score(lang, pred_norm, ref_norm)
    dflow = dataflow_match_score(lang, pred_norm, ref_norm)

    codebleu = alpha * bleu + beta * wbleu + gamma * syn + delta * dflow
    return CodeBLEUScore(bleu=bleu, weighted_bleu=wbleu, syntax=syn, dataflow=dflow, codebleu=codebleu)


