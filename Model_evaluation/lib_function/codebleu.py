RE_LINE_COMMENT_VHDL = re.compile(r"--.*?$", re.M)

def normalize_code(code: str, lang: str = "") -> str:
    """
    Normalize code for metric stability:
      - strip comments (language-aware)
      - collapse whitespace
      - keep content otherwise unchanged
    """
    if code is None:
        return ""
    s = str(code)

    # strip comments
    if lang == "vhdl":
        s = RE_LINE_COMMENT_VHDL.sub(" ", s)
        # VHDL block comments don't exist in standard VHDL
    else:
        s = RE_BLOCK_COMMENT_C.sub(" ", s)
        s = RE_LINE_COMMENT_C.sub(" ", s)

    # normalize whitespace
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


TOKEN_RE = re.compile(
    r"""
    (?:0x[0-9A-Fa-f]+)                         # hex
  | (?:\d+\.\d+|\d+)                            # number
  | (?:[A-Za-z_]\w*)                            # identifier/keyword
  | (?:==|!=|<=|>=|<<|>>|::|:=|->|=>|\+\+|--)   # multi-char ops
  | (?:[^\s])                                   # any single non-space char
""",
    re.VERBOSE,
)

def code_tokenize(code: str) -> List[str]:
    """
    Lightweight tokenizer for code-like text.
    """
    if not code:
        return []
    return TOKEN_RE.findall(code)


