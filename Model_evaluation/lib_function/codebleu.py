# -------------- TOKENIZER --------------
def code_tokenize(code: str):
    """
    Universal code tokenizer suitable for VHDL, SystemVerilog, Chisel, HLS.
    """
    token_pattern = (
        r"[A-Za-z_][A-Za-z0-9_]*|"     # words/identifiers
        r"\d+|"                        # numbers
        r"<=|>=|:=|=>|/=|"             # multi-char ops
        r"[+\-*/=&|^~<>():;.,\"]|"     # 1-char ops/symbols
        r"'.*?'"                       # quoted char
    )
    return re.findall(token_pattern, code)


# -------------- NORMALIZATION (same as EM) --------------
def normalize_code(code: str) -> str:
    c = code

    # Remove comments
    c = re.sub(r"--.*", "", c)               # VHDL
    c = re.sub(r"//.*", "", c)               # C-like
    c = re.sub(r"/\*[\s\S]*?\*/", "", c)     # multi-line

    # Strip and collapse whitespace
    lines = [ln.strip() for ln in c.splitlines()]
    lines = [ln for ln in lines if ln]       # remove empty
    lines = [re.sub(r"\s+", " ", ln) for ln in lines]

    return "\n".join(lines)


# -------------- SIMPLIFIED CODEBLEU --------------
def evaluate_bleu(prediction: str, reference: str) -> float:
    """
    A simplified CodeBLEU-like metric:
    - removes comments & whitespace
    - tokenizes code
    - computes BLEU
    """
    pred_norm = normalize_code(prediction)
    ref_norm  = normalize_code(reference)

    pred_tokens = code_tokenize(pred_norm)
    ref_tokens  = code_tokenize(ref_norm)

    smoothie = SmoothingFunction().method1
    score = sentence_bleu([ref_tokens], pred_tokens, smoothing_function=smoothie)

    return score


