def _wrap_for_parse(lang: str, code: str) -> str:
    """
    Minimal wrapper to make snippets parseable.
    These wrappers are intentionally tiny and deterministic.
    """
    if lang == "chisel":
        return f"object __WRAP__ {{\n{code}\n}}\n"
    if lang == "systemverilog":
        return f"module __wrap__();\n{code}\nendmodule\n"
    if lang == "vhdl":
        return (
            "library ieee;\nuse ieee.std_logic_1164.all;\n"
            "entity __wrap__ is end entity;\n"
            "architecture __a__ of __wrap__ is\n"
            "begin\n"
            f"{code}\n"
            "end architecture;\n"
        )
    if lang == "hls":
        # wrap C/C++ code into a function
        return f"void __wrap__() {{\n{code}\n}}\n"
    return code


def _load_language_single_so(so_path: str, candidates: List[str]) -> Optional[Language]:
    """
    Load a tree-sitter Language from a single-language .so by trying candidate names.
    """
    if Parser is None or Language is None:
        return None
    if not so_path:
        return None
    if not Path(so_path).exists():
        return None

    last_err: Optional[Exception] = None
    for name in candidates:
        try:
            return Language(so_path, name)
        except Exception as e:
            last_err = e
    # If needed, uncomment for debug:
    # print(f"[Tree-sitter] Failed to load {so_path} with {candidates}: {last_err}")
    return None


def _get_ts_parser(lang: str) -> Optional[Parser]:
    """
    Cached parser per language.
    For HLS, lang should be "hls" but internally we might use cpp/c.
    """
    if Parser is None or Language is None:
        return None

    if lang in _PARSER_CACHE:
        return _PARSER_CACHE[lang]

    # map high-level language to so file + candidates
    if lang == "chisel":
        so = TS_SO_PATHS["chisel"]
        cand = TS_LANG_CANDIDATES["chisel"]
    elif lang == "systemverilog":
        so = TS_SO_PATHS["systemverilog"]
        cand = TS_LANG_CANDIDATES["systemverilog"]
    elif lang == "vhdl":
        so = TS_SO_PATHS["vhdl"]
        cand = TS_LANG_CANDIDATES["vhdl"]
    elif lang == "hls":
        # default to cpp parser for HLS snippets
        so = TS_SO_PATHS["cpp"]
        cand = TS_LANG_CANDIDATES["cpp"]
    else:
        return None

    language = _load_language_single_so(so, cand)
    if language is None:
        return None

    parser = Parser()
    parser.set_language(language)
    _PARSER_CACHE[lang] = parser
    return parser


def _collect_node_types(node, bag: Dict[str, int]) -> None:
    bag[node.type] = bag.get(node.type, 0) + 1
    for ch in node.children:
        _collect_node_types(ch, bag)


def multiset_f1(ref_bag: Dict[str, int], pred_bag: Dict[str, int]) -> float:
    """
    Multiset F1 based on node-type count overlap.
    """
    if not ref_bag and not pred_bag:
        return 1.0
    if not ref_bag or not pred_bag:
        return 0.0

    inter = 0
    for k, vref in ref_bag.items():
        vpred = pred_bag.get(k, 0)
        inter += min(vref, vpred)

    sum_ref = sum(ref_bag.values())
    sum_pred = sum(pred_bag.values())
    if sum_ref == 0 or sum_pred == 0:
        return 0.0

    precision = inter / sum_pred
    recall = inter / sum_ref
    return (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0


def syntax_match_score(lang: str, pred: str, ref: str) -> float:
    """
    Tree-sitter AST node-type multiset F1.
    If tree-sitter isn't available/configured, returns 0.0.
    """
    parser = _get_ts_parser(lang)
    if parser is None:
        return 0.0

    pred_w = _wrap_for_parse(lang, pred).encode("utf-8", errors="ignore")
    ref_w  = _wrap_for_parse(lang, ref).encode("utf-8", errors="ignore")

    try:
        t_pred = parser.parse(pred_w)
        t_ref = parser.parse(ref_w)

        bag_pred: Dict[str, int] = {}
        bag_ref: Dict[str, int] = {}
        _collect_node_types(t_pred.root_node, bag_pred)
        _collect_node_types(t_ref.root_node, bag_ref)

        return multiset_f1(bag_ref, bag_pred)
    except Exception:
        return 0.0


