def make_keyword_weight_map(keywords: Set[str], base_weight: float = 1.0) -> Dict[str, float]:
    return {k: base_weight for k in keywords}

def weighted_sentence_bleu(
    ref_tokens: List[str],
    pred_tokens: List[str],
    weights_map: Dict[str, float],
    default_w: float = 0.5
) -> float:
    """
    A practical weighted BLEU:
    Expand tokens proportionally to weights to bias n-gram overlap.
    Weight in [0,1] -> repeats in [1..3].
    """
    def expand(tokens: List[str]) -> List[str]:
        out: List[str] = []
        for t in tokens:
            w = weights_map.get(t, default_w)
            if w >= 0.85:
                rep = 3
            elif w >= 0.65:
                rep = 2
            else:
                rep = 1
            out.extend([t] * rep)
        return out

    smoothie = SmoothingFunction().method1
    ref_exp = expand(ref_tokens)
    pred_exp = expand(pred_tokens)
    return sentence_bleu([ref_exp], pred_exp, smoothing_function=smoothie)


