# ---- Chisel/Scala ----
RE_SCALA_VAL = re.compile(r'(?m)^\s*(?:val|var)\s+([A-Za-z_]\w*)\s*(?::[^=]+)?=\s*(.+)$')
RE_SCALA_ASSIGN = re.compile(r'(?m)^\s*([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)\s*(?::=|=)\s*(.+)$')
RE_SCALA_ID = re.compile(r'\b([A-Za-z_]\w*)\b')
SCALA_STOP = {
    "val","var","def","class","object","trait","extends","with","new","if","else","for","while","match",
    "case","return","true","false","null","this","super","import","package"
}

def dataflow_edges_chisel(code: str) -> Set[Tuple[str, str]]:
    edges: Set[Tuple[str, str]] = set()

    for m in RE_SCALA_VAL.finditer(code):
        lhs, rhs = m.group(1), m.group(2)
        uses = [x for x in RE_SCALA_ID.findall(rhs) if x not in SCALA_STOP]
        for u in uses:
            if u != lhs:
                edges.add((lhs, u))

    for m in RE_SCALA_ASSIGN.finditer(code):
        lhs_full, rhs = m.group(1), m.group(2)
        lhs = lhs_full.split(".")[-1]
        uses = [x for x in RE_SCALA_ID.findall(rhs) if x not in SCALA_STOP]
        for u in uses:
            if u != lhs:
                edges.add((lhs, u))

    return edges


def dataflow_match_score(lang: str, pred: str, ref: str) -> float:
    if lang == "hls":
        return f1_from_sets(dataflow_edges_hls(ref), dataflow_edges_hls(pred))
    if lang == "systemverilog":
        return f1_from_sets(dataflow_edges_systemverilog(ref), dataflow_edges_systemverilog(pred))
    if lang == "vhdl":
        return f1_from_sets(dataflow_edges_vhdl(ref), dataflow_edges_vhdl(pred))
    if lang == "chisel":
        return f1_from_sets(dataflow_edges_chisel(ref), dataflow_edges_chisel(pred))
    return 0.0


